<script lang="ts">
	import type { FragmentView, FrameUse, Layer, RoomParts } from '#lib/engine/types.ts';
	import Heading from '../atoms/Heading.svelte';
	import FragmentItem from '../molecules/FragmentItem.svelte';
	import HelpNote from '../molecules/HelpNote.svelte';
	import PartItem from '../molecules/PartItem.svelte';
	import SectionRule from '../molecules/SectionRule.svelte';

	interface Props {
		/** The current room id. */
		room: string;
		fragments: FragmentView[];
		/** The things and exits of the generated layers. */
		parts?: RoomParts;
		/** The action frame used for the last action, or null. */
		frame?: FrameUse | null;
		/** The highlighted fragment index, or null. */
		focus?: number | null;
		/** The time of day and the phase, for the footer. */
		time: string;
		phase: string;
		onfocus?: (index: number | null) => void;
		/** Open the writer for a room fragment. When set, each fragment has an "Edit" button. */
		onedit?: (index: number) => void;
	}

	let { room, fragments, parts, frame = null, focus = null, time, phase, onfocus, onedit }: Props = $props();

	const layers: Layer[] = ['base', 'ambient', 'event', 'objects', 'characters', 'exits'];
	const generated: Partial<Record<Layer, string>> = {
		objects: 'The runtime makes this layer from the things in the room.',
		exits: 'The runtime makes this layer from the visible exits.'
	};
	const partsOf = (layer: Layer) =>
		layer === 'objects' ? (parts?.objects ?? []) : layer === 'exits' ? (parts?.exits ?? []) : [];

	const groups = $derived(layers.map((layer) => ({ layer, items: fragments.filter((f) => f.layer === layer) })));

	function scopeLabel(scope: string): string {
		if (scope === 'story') return 'the story';
		const [kind, id] = scope.split(':');
		return `${kind}.${id}`;
	}

	function frameMeta(f: { mode: string; condition: string | null }): string {
		return [f.mode.replace('_', ' '), f.condition ? `when ${f.condition}` : ''].filter(Boolean).join(' · ');
	}

	function meta(f: FragmentView): string {
		const parts: string[] = [f.mode.replace('_', ' ')];
		if (f.condition) parts.push(`when ${f.condition}`);
		if (f.replaces) parts.push('replaces');
		return parts.join(' · ');
	}
</script>

<!--
	Shows how the runtime assembles the room text now: each layer in order,
	each fragment with its state. Hidden fragments show why they are hidden.
-->
<div class="assembly">
	<header class="head">
		<Heading level={2} id="assembly-title">Assembly · room.{room}</Heading>
		<HelpNote id="assembly" topic="Assembly">
			The player reads the shown fragments in this order: layer by layer, then by position in the layer. The numbers
			are the same as the numbers in the transcript. Layers in a dashed box are generated by the runtime from the
			things and exits of the room. You do not write them as fragments.
		</HelpNote>
	</header>

	{#if frame}
		<!-- The action frame of the last action: author text around the response, and why each part showed. -->
		<section class="layer frame">
			<SectionRule title="last action" tag="frame" />
			<p class="frame-summary">
				<code>{frame.verb}</code> uses the frame on {scopeLabel(frame.scope)}. action.repeat = {frame.repeat}, action.count
				= {frame.count}, action.total = {frame.total}.
			</p>
			{#each frame.parts as part (part.part)}
				<ul aria-label="{part.part} fragments">
					{#each part.fragments as f (f.index)}
						<PartItem
							label="{part.part} {f.index + 1}"
							text={f.text}
							detail={frameMeta(f)}
							shown={f.shown}
							why={f.why}
							within="response"
						/>
					{/each}
				</ul>
			{/each}
		</section>
	{/if}

	{#each groups as g (g.layer)}
		{@const isGenerated = !!generated[g.layer]}
		<section class="layer" class:generated={isGenerated}>
			<SectionRule title={g.layer} tag={isGenerated ? 'generated' : undefined} />
			{#if g.items.length}
				<ul>
					{#each g.items as f (f.index)}
						<FragmentItem
							number={f.index + 1}
							text={f.text}
							variants={f.variants}
							meta={meta(f)}
							shown={f.shown}
							why={f.why}
							active={focus === f.index}
							onactivate={(on) => onfocus?.(on ? f.index : null)}
							onedit={onedit ? () => onedit(f.index) : undefined}
						/>
					{/each}
				</ul>
			{:else if generated[g.layer]}
				<p class="empty">{generated[g.layer]}</p>
				{#if partsOf(g.layer).length}
					<ul>
						{#each partsOf(g.layer) as part (part.id)}
							<PartItem label={part.label} text={part.text} detail={part.detail} shown={part.shown} why={part.why} />
						{/each}
					</ul>
				{:else}
					<p class="empty">{g.layer === 'objects' ? 'No things are in this room.' : 'This room has no exits.'}</p>
				{/if}
			{:else}
				<p class="empty">This layer has no fragments.</p>
			{/if}
		</section>
	{/each}

	<footer>
		<span>time {time} · {phase}</span>
	</footer>
</div>

